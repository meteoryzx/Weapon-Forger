import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { PNG } from 'pngjs';

const directory='output/playwright/grinder-integration';
await mkdir(directory,{recursive:true});
const browser=await chromium.launch({channel:'msedge'});
const results=[];
try {
  for(const viewport of [{width:1440,height:900},{width:390,height:844}]){
    const page=await browser.newPage({viewport});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto('http://127.0.0.1:4199/?accept=grind');
    await page.locator('body[data-camera-state=settled]').waitFor();
    const inspect=()=>page.evaluate(()=>window.__forgeInspect());
    const start=await inspect(),g=start.grind;
    assert.equal(start.station,'grind');
    assert.equal(g.model,'belt-grinder');
    assert.ok(Math.abs(g.billetBounds.min.y-g.restY)<1e-6,'billet rests on support');
    assert.ok(Math.abs(g.billetBounds.max.x-g.frontX)<1e-6,'billet leading edge touches belt');
    assert.ok(Math.abs(start.camera.position[2]-start.camera.target[2])<1e-6,'camera faces world right');
    assert.ok(start.camera.position[0]<start.camera.target[0]);
    assert.ok(g.contact,'initial contact');
    const canvas=page.locator('#game'),bounds=await canvas.boundingBox();
    assert.ok(start.points.billet.x>0&&start.points.billet.x<bounds.width);
    assert.ok(start.points.billet.y>0&&start.points.billet.y<bounds.height);
    await page.screenshot({path:directory+'/'+viewport.width+'-start.png'});
    const first=PNG.sync.read(await canvas.screenshot());
    await page.waitForTimeout(150);
    const second=PNG.sync.read(await canvas.screenshot());
    let changed=0;
    for(let i=0;i<first.data.length;i+=4)if(Math.abs(first.data[i]-second.data[i])+Math.abs(first.data[i+1]-second.data[i+1])+Math.abs(first.data[i+2]-second.data[i+2])>20)changed++;
    assert.ok(changed>50,'moving belt visibly changes pixels');
    const count=async()=>Number(await page.locator('body').getAttribute('data-acceptance-operation-count'));
    const drag=async(modifiers=[])=>{
      const s=await inspect(),p=s.points.billet;
      for(const key of modifiers)await page.keyboard.down(key);
      await page.mouse.move(bounds.x+p.x,bounds.y+p.y);
      await page.mouse.down();
      await page.mouse.move(bounds.x+p.x+35,bounds.y+p.y,{steps:10});
      await page.waitForTimeout(240);
      await page.mouse.up();
      for(const key of modifiers)await page.keyboard.up(key);
    };
    await canvas.focus();
    await page.keyboard.press('s');
    assert.equal((await inspect()).grind.contact,null);
    const initialCount=await count();
    await drag();
    assert.equal(await count(),initialCount,'moving retracted billet does not grind');
    await page.keyboard.press('w');
    assert.ok((await inspect()).grind.contact,'feeding back restores contact');
    await drag(['Shift']);
    assert.equal(await count(),initialCount,'horizontal placement does not grind');
    assert.notEqual((await inspect()).grind.pose.z,0);
    await page.keyboard.press('r');
    await page.locator('body[data-camera-state=settled]').waitFor();
    const poseBefore= (await inspect()).grind.pose;
    await page.mouse.wheel(0,-120);
    await page.keyboard.press('a');
    await page.keyboard.press('q');
    const poseAfter= (await inspect()).grind.pose;
    assert.notEqual(poseAfter.angle,poseBefore.angle,'wheel controls X rotation');
    assert.notEqual(poseAfter.yaw,poseBefore.yaw,'A/D controls Y rotation');
    assert.notEqual(poseAfter.roll,poseBefore.roll,'Q/E controls Z rotation');
    await page.keyboard.press('r');
    await page.locator('body[data-camera-state=settled]').waitFor();
    await drag();
    assert.ok(await count() > 0,'held contact continuously invokes forge operations');
    await page.screenshot({path:directory+'/'+viewport.width+'-after-grind.png'});
    const end=await inspect();
    results.push({viewport,changedPixels:changed,errors,start,end,operations:await count()});
    assert.deepEqual(errors,[]);
    await page.close();
  }
  await writeFile(directory+'/report.json',JSON.stringify(results,null,2)+'\n');
  console.log(results.map(r=>({viewport:r.viewport,changedPixels:r.changedPixels,operations:r.operations,errors:r.errors})));
}finally{await browser.close();}
